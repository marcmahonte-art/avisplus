/**
 * AVIS+ — Référentiel des catégories d'entreprises.
 *
 * Source : `categorie.md` (catégories d'entreprises à prospecter à Ouagadougou).
 * Ce référentiel sert à **classer les pages digitales** : chaque entreprise est
 * rattachée à une catégorie principale et, si utile, à une sous-catégorie précise.
 *
 * Note sur la fidélité au document source :
 * - Les sections 1 à 20 de `categorie.md` sont reprises telles quelles.
 * - La section 1 (« Priorité maximale ») regroupe six activités distinctes : elles
 *   sont éclatées en catégories autonomes (Restauration, Hôtellerie, Beauté, Mode,
 *   Cosmétiques, Commerces spécialisés) car c'est ainsi qu'un commerçant se reconnaît.
 * - La section 18 (« Mode et beauté — sous-segment spécialisé ») est un sous-ensemble
 *   de « Beauté et soins esthétiques » : ses entrées ont été fusionnées pour éviter
 *   deux catégories beauté concurrentes dans l'interface.
 * - Les groupes de priorité commerciale A / B / C du document sont conservés dans le
 *   champ `priority`, à titre indicatif.
 */

/** Groupe d'effort commercial défini dans `categorie.md`. */
export type CategoryPriority = "A" | "B" | "C";

export interface BusinessCategoryDef {
  /** Identifiant stable, utilisé en base et dans les URL de filtre. */
  id: string;
  /** Libellé affiché dans l'interface. */
  label: string;
  /** Phrase courte expliquant ce que regroupe la catégorie. */
  description: string;
  /** Priorité commerciale indicative (`categorie.md`). */
  priority: CategoryPriority;
  /** Sous-catégories proposées à la saisie. */
  subcategories: readonly string[];
}

