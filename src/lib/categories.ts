/** Catégorie utilisée lorsqu'aucune n'est renseignée. */
export const FALLBACK_CATEGORY_ID = "services-b2b";

/** Retourne la définition d'une catégorie, ou `undefined` si l'identifiant est inconnu. */
export function getCategoryById(id: string | null | undefined): BusinessCategoryDef | undefined {
  if (!id) return undefined;
  return BUSINESS_CATEGORIES.find((category) => category.id === id);
}

/** Libellé d'une catégorie, avec repli lisible si l'identifiant est inconnu. */
export function getCategoryLabel(id: string | null | undefined): string {
  return getCategoryById(id)?.label ?? "Non classée";
}

/** Sous-catégories proposées pour une catégorie donnée. */
export function getSubcategories(id: string | null | undefined): readonly string[] {
  return getCategoryById(id)?.subcategories ?? [];
}

/**
 * Construit le libellé complet affiché partout : « Restauration › Maquis ».
 * Retourne « Non classée » si aucune catégorie n'est renseignée.
 */
export function formatCategoryLabel(
  categoryId: string | null | undefined,
  subcategory?: string | null,
): string {
  const category = getCategoryById(categoryId);
  if (!category) return "Non classée";
  if (subcategory && subcategory.trim() !== "") {
    return `${category.label} › ${subcategory}`;
  }
  return category.label;
}

/** Indique si un identifiant de catégorie existe dans le référentiel. */
export function isKnownCategoryId(id: string | null | undefined): boolean {
  return getCategoryById(id) !== undefined;
}
